def _match_topic(
    text: str,
    topics: list[tuple[list[str], str]],
    fallback: str,
) -> str:
    """Return the first topic response whose keyword appears in *text*."""
    for keywords, response in topics:
        if any(kw in text for kw in keywords):
            return response
    return fallback


def career_reply(message: str, language: str = "English") -> str:
    """
    Return rule-based career guidance for *message* in the requested *language*.

    Parameters
    ----------
    message  : user's question or topic
    language : "English" (default) or "Kannada"

    Note: Responses are transparent, rule-based guidance — not live AI output.
    """
    text = (message or "").strip().lower()

    if not text:
        if language.lower().startswith("kannada"):
            return "ನಿಮ್ಮ ವೃತ್ತಿ ಪ್ರಶ್ನೆ ಅಥವಾ ಗುರಿ ಪಾತ್ರ ತಿಳಿಸಿ."
        return "Tell me your target role or the career question you would like help with."

    if language.lower().startswith("kannada"):
        return _match_topic(text, _KN_TOPICS, _KN_FALLBACK)

    return _match_topic(text, _EN_TOPICS, _EN_FALLBACK)
